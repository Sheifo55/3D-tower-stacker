TextRenderer::TextRenderer() : VAO(0), VBO(0), fontTexture(0) {}

TextRenderer::~TextRenderer() {
    if (VAO) glDeleteVertexArrays(1, &VAO);
    if (VBO) glDeleteBuffers(1, &VBO);
    if (fontTexture) glDeleteTextures(1, &fontTexture);
}

void TextRenderer::init(int screenWidth, int screenHeight) {
    this->screenWidth = screenWidth;
    this->screenHeight = screenHeight;
    projection = glm::ortho(0.0f, static_cast<float>(screenWidth), 0.0f, static_cast<float>(screenHeight));

    generateFontAtlas();

    glGenVertexArrays(1, &VAO);
    glGenBuffers(1, &VBO);

    glBindVertexArray(VAO);
    glBindBuffer(GL_ARRAY_BUFFER, VBO);
    // 2D Quad requires 6 vertices of 4 floats each (x, y, u, v)
    glBufferData(GL_ARRAY_BUFFER, sizeof(float) * 6 * 4, NULL, GL_DYNAMIC_DRAW);
    
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 4, GL_FLOAT, GL_FALSE, 4 * sizeof(float), 0);

    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindVertexArray(0);
}

void TextRenderer::generateFontAtlas() {
    // Generate an atlas image (e.g. 128x128 pixels, 1 byte per pixel)
    const int atlasWidth = 128;
    const int atlasHeight = 128;
    std::vector<unsigned char> atlasData(atlasWidth * atlasHeight, 0);

    int startChar = 32;
    int endChar = 127;
    int cols = 16;
    
    // Each character is 5x7 pixels. We will store it in an 8x8 block in the atlas to have spacing.
    int blockW = 8;
    int blockH = 8;

    for (int i = startChar; i <= endChar; ++i) {
        int idx = i - startChar;
        int row = idx / cols;
        int col = idx % cols;

        int startX = col * blockW;
        int startY = row * blockH;

        for (int x = 0; x < 5; ++x) {
            unsigned char colData = font5x7[idx][x];
            for (int y = 0; y < 7; ++y) {
                if ((colData >> y) & 1) {
                    atlasData[(startY + y) * atlasWidth + (startX + x)] = 255;
                }
            }
        }

        Character character = {
            static_cast<float>(startX) / atlasWidth,
            static_cast<float>(startY) / atlasHeight,
            static_cast<float>(startX + 5) / atlasWidth,
            static_cast<float>(startY + 7) / atlasHeight,
            5.0f,
            7.0f
        };
        characters[i] = character;
    }

    glGenTextures(1, &fontTexture);
    glBindTexture(GL_TEXTURE_2D, fontTexture);
    // Setup texture parameters
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    // Nearest neighbor filtering keeps the font crisp
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);

    // Upload texture to GPU
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RED, atlasWidth, atlasHeight, 0, GL_RED, GL_UNSIGNED_BYTE, atlasData.data());
    glBindTexture(GL_TEXTURE_2D, 0);
}

void TextRenderer::updateScreenSize(int width, int height) {
    this->screenWidth = width;
    this->screenHeight = height;
    projection = glm::ortho(0.0f, static_cast<float>(width), 0.0f, static_cast<float>(height));
}

void TextRenderer::renderText(Shader& shader, const std::string& text, float x, float y, float scale, const glm::vec3& color) {
    shader.use();
    shader.setMat4("projection", projection);
    shader.setVec3("textColor", color);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, fontTexture);
    shader.setInt("textTexture", 0);

    glBindVertexArray(VAO);

    // Scaling the 5x7 characters natively will look tiny, scale by 4.0 as base to make it readable.
    float baseScale = 4.0f;
    float finalScale = scale * baseScale;
    
    // Space between characters
    float spacing = 1.0f * finalScale;

    for (auto c : text) {
        if (characters.find(c) == characters.end()) {
            c = '?'; // Fallback
        }

        Character ch = characters[c];

        float xpos = x;
        float ypos = y;

        float w = ch.width * finalScale;
        float h = ch.height * finalScale;

        // VBO expects x, y, u, v
        // We are drawing from top-left, but OpenGL ortho projection bottom is 0. 
        // We will make 'y' the bottom baseline, so top is y + h.
        float vertices[6][4] = {
            { xpos,     ypos + h,   ch.u1, ch.v1 },
            { xpos,     ypos,       ch.u1, ch.v2 },
            { xpos + w, ypos,       ch.u2, ch.v2 },

            { xpos,     ypos + h,   ch.u1, ch.v1 },
            { xpos + w, ypos,       ch.u2, ch.v2 },
            { xpos + w, ypos + h,   ch.u2, ch.v1 }
        };

        glBindBuffer(GL_ARRAY_BUFFER, VBO);
        glBufferSubData(GL_ARRAY_BUFFER, 0, sizeof(vertices), vertices); 
        glBindBuffer(GL_ARRAY_BUFFER, 0);

        glDrawArrays(GL_TRIANGLES, 0, 6);

        // Advance cursor (width + spacing)
        x += (ch.width * finalScale) + spacing;
    }

    glBindVertexArray(0);
    glBindTexture(GL_TEXTURE_2D, 0);
}
